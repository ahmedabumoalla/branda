import {notFound,redirect} from 'next/navigation';
import Link from 'next/link';
import {createClient} from '@/lib/supabase/server';
import {readErpStaffShell} from '@/lib/data/erp-staff-shell';
import {readBranchContext} from '@/lib/data/erp-branches';
import {withErpRequest} from '@/lib/erp/request-context';
import {erpHref} from '@/lib/erp/navigation';
import {StaffShell} from '@/components/erp/staff-shell';
import {SystemAppearance} from '@/components/erp/settings/appearance';
import s from '@/components/erp/staff-shell.module.css';
import Store from '@/app/dashboard/system/store/[[...segments]]/page';
import Manufacturing from '@/app/dashboard/system/manufacturing/[[...path]]/page';
import Tasks from '@/app/dashboard/system/tasks/[[...parts]]/page';
import Bookings from '@/app/dashboard/system/bookings/page';
import BookingSettings from '@/app/dashboard/system/bookings/settings/page';
import Contracting from '@/app/dashboard/system/contracting/[[...segments]]/page';
import Installments from '@/app/dashboard/system/installments/page';
import InstallmentSchedule from '@/app/dashboard/system/installments/schedule/page';
import InstallmentSettings from '@/app/dashboard/system/installments/settings/page';
import Commissions from '@/app/dashboard/system/commissions/[[...parts]]/page';
import Rentals from '@/app/dashboard/system/rentals/[[...section]]/page';
import WorkOrders from '@/app/dashboard/system/work-orders/[[...segments]]/page';
import Workflows from '@/app/dashboard/system/workflows/[[...segments]]/page';
import Assets from '@/app/dashboard/system/assets/[[...path]]/page';
import Custody from '@/app/dashboard/system/employee-assets/[[...path]]/page';
import Employees from '@/app/dashboard/system/employees/[[...parts]]/page';
import Organization from '@/app/dashboard/system/organization/[[...parts]]/page';
import Attendance from '@/app/dashboard/system/attendance/[[...path]]/page';
import Payroll from '@/app/dashboard/system/payroll/[[...parts]]/page';
import Templates from '@/app/dashboard/system/templates/[[...segments]]/page';
import Customers from '@/app/dashboard/system/customers/[[...segments]]/page';
import Insurance from '@/app/dashboard/system/insurance/[[...segments]]/page';
import Credits from '@/app/dashboard/system/credits/[[...segments]]/page';
import Memberships from '@/app/dashboard/system/memberships/[[...segments]]/page';
import CustomerAttendance from '@/app/dashboard/system/customer-attendance/page';
import Time from '@/app/dashboard/system/time/[[...segments]]/page';
import Accounting from '@/app/dashboard/system/accounting/[[...parts]]/page';
import Finance from '@/app/dashboard/system/finance/[[...parts]]/page';
import Inventory from '@/app/dashboard/system/inventory/[[...path]]/page';
import Purchases from '@/app/dashboard/system/purchases/[[...segments]]/page';
import Cheques from '@/app/dashboard/system/cheques/[[...segments]]/page';
import Reports from '@/app/dashboard/system/reports/[[...parts]]/page';
import Branches from '@/app/dashboard/system/branches/[[...path]]/page';
import Requests from '@/app/dashboard/system/requests/[[...segments]]/page';
export const dynamic='force-dynamic';
export const runtime='nodejs';
export default async function Page({params,searchParams}:{params:Promise<{slug:string;parts?:string[]}>;searchParams:Promise<Record<string,string|string[]|undefined>>}) {
 const {slug,parts=[]}=await params;
 if(!/^[a-z0-9-]{1,120}$/.test(slug))notFound();
 const client=await createClient();
 const {data:{user}}=await client.auth.getUser();
 if(!user)redirect(`/finance/${slug}/system/login`);
 const shell=await readErpStaffShell(slug);
 const branch=await readBranchContext(slug);
 const [module,...rest]=parts;
 const domain=shell.domains.find(d=>d.href===`/dashboard/system/${module}`);
 if(module&&!domain)notFound();
 if(branch.scope.branchId?!branch.branches.some(b=>b.id===branch.scope.branchId):branch.requiresSelection){return <StaffShell slug={slug} name={shell.cafe.name} domains={shell.domains}><SystemAppearance slug={slug}><section role="status" className={s.home}><p>{branch.branches.length?'اختر فرع العمل من أعلى الصفحة لعرض سجلاته':'لا يوجد فرع عمل متاح لحسابك تواصل مع مسؤول العلامة لربط ملفك بأحد الفروع'}</p></section></SystemAppearance></StaffShell>;}
 const q=await searchParams;
 const flat=Promise.resolve(Object.fromEntries(Object.entries(q).map(([k,v])=>[k,Array.isArray(v)?v[0]:v])));
 const props={params:Promise.resolve({segments:rest,path:rest,parts:rest,section:rest}),searchParams:flat};
 const content=module?await withErpRequest(slug,async()=>{
   switch(module){
    case 'store':return Store(props);case 'manufacturing':return Manufacturing(props);case 'tasks':return Tasks(props);
    case 'bookings':if(rest.length>1||rest[0]&&rest[0]!=='settings')notFound();return rest[0]?BookingSettings():Bookings();
    case 'contracting':return Contracting(props);
    case 'installments':if(rest.length>1||rest[0]&&!['settings','schedule'].includes(rest[0]))notFound();return rest[0]==='settings'?InstallmentSettings():rest[0]==='schedule'?InstallmentSchedule():Installments();
    case 'commissions':return Commissions(props);case 'rentals':return Rentals(props);case 'work-orders':return WorkOrders(props);case 'workflows':return Workflows(props);
    case 'assets':return Assets(props);case 'employee-assets':return Custody(props);case 'employees':return Employees(props);case 'organization':return Organization(props);
    case 'attendance':return Attendance(props);case 'payroll':return Payroll(props);case 'templates':return Templates(props);case 'customers':return Customers(props);case 'credits':return Credits(props);case 'insurance':return Insurance(props);case 'memberships':return Memberships(props);case 'customer-attendance':if(rest.length)notFound();return CustomerAttendance();case 'time':return Time(props);
    case 'accounting':return Accounting(props);
    case 'finance':return Finance(props);
    case 'inventory':return Inventory(props);
    case 'purchases':return Purchases(props);
    case 'cheques':return Cheques(props);
    case 'reports':return Reports(props);
    case 'requests':return Requests(props);
    case 'branches':return Branches(props);
    default:notFound();
   }
 }):<div className={s.home}>{shell.domains.map(d=><Link key={d.key} href={erpHref(d.href,slug)}>{d.label}</Link>)}{!shell.domains.length&&<p className={s.empty}>لا توجد أقسام متاحة لحسابك تواصل مع مسؤول العلامة لتعيين صلاحياتك</p>}</div>;
 return <StaffShell slug={slug} name={shell.cafe.name} domains={shell.domains}><SystemAppearance slug={slug}>{content}</SystemAppearance></StaffShell>;
}
