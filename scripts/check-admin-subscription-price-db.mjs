import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import path from "node:path";
import { tmpdir } from "node:os";
import { pathToFileURL } from "node:url";

const modulePath = process.env.PGLITE_MODULE ?? path.join(tmpdir(), "branda-loyalty-sql-tests/node_modules/@electric-sql/pglite/dist/index.js");
const { PGlite } = await import(pathToFileURL(modulePath).href);
const db = new PGlite();
const cafe = "20000000-0000-4000-8000-000000000001";
const sub = "20000000-0000-4000-8000-000000000002";
const admin = "20000000-0000-4000-8000-000000000003";
await db.exec(`
  create role anon; create role authenticated;
  create schema auth;
  create function auth.uid() returns uuid language sql as $$select nullif(current_setting('test.actor',true),'')::uuid$$;
  create function public.is_platform_admin() returns boolean language sql as $$select auth.uid()='SELF'::uuid$$;
  create table public.platform_plans(id text primary key,active boolean);
  create table public.subscriptions(id uuid primary key, cafe_id uuid, plan_id text, status text, activation_source text, started_at timestamptz, expires_at timestamptz, amount_sar numeric);
  insert into public.platform_plans values('test',true);
  insert into public.subscriptions values('SUB','CAFE','test','trialing','legacy',now(),now()+interval '1 day',0);
`.replaceAll("SELF", admin).replaceAll("SUB", sub).replaceAll("CAFE", cafe));
await db.exec(await readFile(new URL("../supabase/migrations/20261121213259_admin_subscription_manual_price.sql", import.meta.url), "utf8"));
const save = (price, expected, brand = cafe) => db.query("select public.set_admin_subscription_price($1,$2,$3,$4)", [brand,sub,price,expected]);
await db.exec("set role anon");
await assert.rejects(() => save(75,null), {code:"42501"});
await db.exec("reset role; set role authenticated");
await assert.rejects(() => save(75,null), {code:"42501"});
await db.exec(`set test.actor='${admin}'`);
await assert.rejects(() => save(50,null,admin), {code:"P0002"});
for (const invalid of [-1,75.001,100000000,null]) await assert.rejects(() => save(invalid,null), {code:"22023"});
await save(75.25,null);
await assert.rejects(() => save(20,null), {code:"40001"});
await save(0,75.25);
await assert.rejects(() => db.query("delete from public.admin_subscription_prices"), {code:"42501"});
await db.exec("reset role; update public.subscriptions set expires_at=now()-interval '1 minute'; set role authenticated");
await assert.rejects(() => save(25,0), {code:"P0002"});
await db.exec("reset role");
const result = await db.query("select price_sar,amount_sar,status,updated_by from public.subscriptions join public.admin_subscription_prices on subscription_id=id");
assert.deepEqual(result.rows[0],{price_sar:"0.00",amount_sar:"0",status:"trialing",updated_by:admin});
await db.close();
console.log("Manual subscription price: admin scope, decimal/zero, stale writes, ended trials and payment isolation passed");
