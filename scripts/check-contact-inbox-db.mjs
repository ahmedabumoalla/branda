import assert from "node:assert/strict";
import fs from "node:fs/promises";
import path from "node:path";
import { tmpdir } from "node:os";
import { pathToFileURL } from "node:url";
const { PGlite } = await import(pathToFileURL(process.env.PGLITE_MODULE ?? path.join(tmpdir(), "branda-loyalty-sql-tests/node_modules/@electric-sql/pglite/dist/index.js")).href);
const db = new PGlite();
await db.exec(`CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role BYPASSRLS;
  CREATE TABLE public.platform_contact_requests(id uuid PRIMARY KEY DEFAULT gen_random_uuid(),full_name text NOT NULL,email text NOT NULL,message text NOT NULL,status text DEFAULT 'new' CHECK(status IN ('new','reviewing','closed')),created_at timestamptz DEFAULT now(),updated_at timestamptz DEFAULT now());
  ALTER TABLE public.platform_contact_requests ENABLE ROW LEVEL SECURITY;
  GRANT USAGE ON SCHEMA public TO anon,authenticated,service_role;
  GRANT SELECT ON public.platform_contact_requests TO anon,authenticated;
  CREATE POLICY admin_read ON public.platform_contact_requests FOR SELECT TO authenticated USING(current_setting('test.admin',true)='true');
  CREATE TABLE public.platform_contact_settings(id text PRIMARY KEY,whatsapp text,updated_at timestamptz);
  INSERT INTO public.platform_contact_settings VALUES('main','old',now());
  INSERT INTO public.platform_contact_requests(full_name,email,message) VALUES('Legacy Name','legacy@example.invalid','Legacy message');`);
const before = (await db.query("SELECT to_jsonb(r) AS row FROM public.platform_contact_requests r")).rows[0].row;
await db.exec(await fs.readFile('supabase/migrations/20261031202818_homepage_contact_inbox.sql','utf8'));
const id = n => `00000000-0000-4000-8000-${String(n).padStart(12,'0')}`;
const submit = (n, phone='966500000000',name='Test Name') => db.query('SELECT public.submit_home_contact_request($1,$2,$3,$4,$5,$6)',[id(n),name,phone,'Test Business','Cafe','Test Plan']);
await db.exec('SET ROLE service_role');
await submit(1); await submit(1);
assert.equal((await db.query('SELECT count(*)::int AS count FROM public.platform_contact_requests')).rows[0].count,2,'Retry must be idempotent');
await submit(2); await submit(3);
await assert.rejects(()=>submit(4), /Contact rate limit/);
await assert.rejects(()=>submit(5,'invalid'), /Invalid contact request/);
await assert.rejects(()=>submit(6,'966500000001','x'), /Invalid contact request/);
await db.exec('RESET ROLE; SET ROLE anon');
assert.equal((await db.query('SELECT count(*)::int AS count FROM public.platform_contact_requests')).rows[0].count,0,'Anonymous users cannot read inbox');
await assert.rejects(()=>submit(7),/permission denied/);
await db.exec('RESET ROLE; SET ROLE authenticated');
assert.equal((await db.query('SELECT count(*)::int AS count FROM public.platform_contact_requests')).rows[0].count,0,'Ordinary users cannot read inbox');
await assert.rejects(()=>submit(8),/permission denied/);
await db.exec("SET test.admin='true'");
assert.equal((await db.query('SELECT count(*)::int AS count FROM public.platform_contact_requests')).rows[0].count,4);
await db.exec('RESET ROLE');
const legacy=(await db.query("SELECT to_jsonb(r)-'phone'-'business_name'-'business_type'-'selected_plan' AS row FROM public.platform_contact_requests r WHERE email='legacy@example.invalid'")).rows[0].row;
assert.deepEqual(legacy,before,'Existing email requests preserved');
