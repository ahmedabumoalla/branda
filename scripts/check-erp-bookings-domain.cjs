const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const Module=require('node:module');
const ts=require('typescript');
const source=path.resolve('lib/erp/bookings.ts');
const unit=new Module(source,module);unit.filename=source;unit.paths=Module._nodeModulePaths(path.dirname(source));
unit._compile(ts.transpileModule(fs.readFileSync(source,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText,source);
const {bookingInstant,bookingLocalDate,bookingDateAdd,bookingMonthAdd,bookingSlotAvailable,bookingEventLanes,bookingCommandSchema}=unit.exports;
let checks=0;const eq=(a,b,label)=>{assert.deepEqual(a,b,label);checks++};
eq(bookingInstant('2026-11-15T09:00','Asia/Riyadh'),'2026-11-15T06:00:00.000Z','business timezone used');
eq(bookingLocalDate('2026-11-15T23:00:00Z','Asia/Riyadh'),'2026-11-16T02:00','local date crosses midnight');
assert.throws(()=>bookingInstant('2026-03-08T02:30','America/New_York'));checks++;
eq(bookingInstant('2026-03-08T03:30','America/New_York'),'2026-03-08T07:30:00.000Z','DST after gap');
eq(bookingDateAdd('2028-02-28',1),'2028-02-29','leap day');
eq(bookingMonthAdd('2026-01-31',1),'2026-02-01','month navigation never skips February');
eq(bookingMonthAdd('2026-01-31',-1),'2025-12-01','previous year navigation');
const base={id:'a',revision:1,staff_id:'staff',branch_id:'a',weekday:0,on_date:null,starts:'09:00:00',ends:'17:00:00',closed:false};
eq(bookingSlotAvailable([base],'staff','2026-11-15',540,30,'a'),true,'weekly availability');
eq(bookingSlotAvailable([base],'staff','2026-11-15',1000,30,'a'),false,'full duration must fit');
eq(bookingSlotAvailable([base],'staff','2026-11-15',540,30,'b'),false,'branch isolation');
const closed={...base,weekday:null,on_date:'2026-11-15',closed:true};
eq(bookingSlotAvailable([base,closed],'staff','2026-11-15',540,30,'a'),false,'dated closure overrides weekday');
eq(bookingSlotAvailable([base,closed,{...base,branch_id:'b'}],'staff','2026-11-15',540,30),true,'all branches retains another available branch');
const event=(id,start,end)=>({id,starts_at:`2026-11-15T${start}:00Z`,ends_at:`2026-11-15T${end}:00Z`});
const placements=bookingEventLanes([event('a','09:00','10:00'),event('b','09:30','11:00'),event('c','10:00','11:00'),event('d','11:00','12:00')]);
eq(placements.map(p=>[p.item.id,p.lane,p.lanes]),[['a',0,2],['b',1,2],['c',0,2],['d',0,1]],'connected overlap groups have stable widths and reusable lanes');
eq(bookingCommandSchema.safeParse({action:'invoice',payload:{id:'bad',revision:1}}).success,false,'forged action identifiers rejected');
console.log(JSON.stringify({passed:true,checks,scope:'ERP booking timezone/DST, availability and overlapping calendar layout',at:new Date().toISOString()}));
