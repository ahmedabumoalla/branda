/** Owner uploads always take priority over the original catalog artwork. */
export function teaBakeryProductMedia(product: StandaloneMenuProduct): StandaloneMenuProduct {
  const url = teaBakeryProductImages[product.id];
  if (!url || product.images.length || product.videos.length) return product;
  return { ...product, primaryMediaType: "image", images: [{ url, alt: product.name }] };
}
