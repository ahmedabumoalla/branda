export function knownFrenchLabel(source: string, english?: string | null): string | undefined {
  const name = source.trim();
  const known = menuFrench.get(name);
  if (known) return known;
  for (const key of [english?.trim(), hospitalProductName(name, "en"), hospitalCategoryName(name, "en")]) {
    if (key && Object.hasOwn(financePosFrench, key)) return financePosFrench[key];
  }
  return undefined;
}
